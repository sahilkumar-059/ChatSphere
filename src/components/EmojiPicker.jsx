export default function EmojiPicker({ onEmojiSelect }) {
  const [activeCategory, setActiveCategory] = useState(0);
  const scrollRef = useRef(null);

  const handleEmojiClick = (emoji) => {
    if (onEmojiSelect) {
      onEmojiSelect(emoji);
    }
  };

  const handleCategoryClick = (index) => {
    setActiveCategory(index);
    // Scroll to the category in the grid
    const el = scrollRef.current?.querySelector(`[data-category-index="${index}"]`);
    if (el) {
      el.scrollIntoView({ behavior: "smooth", block: "start" });
    }
  };

  return (
    <div className="emoji-picker-container">
      {/* Category tabs */}
      <div className="emoji-categories">
        {EMOJI_CATEGORIES.map((cat, index) => (
          <button
            key={cat.name}
            className={`emoji-cat-btn ${activeCategory === index ? "active" : ""}`}
            onClick={() => handleCategoryClick(index)}
            title={cat.name}
          >
            {cat.emojis[0]}
          </button>
        ))}
      </div>

      {/* Emoji grid */}
      <div className="emoji-grid-scroll" ref={scrollRef}>
        {EMOJI_CATEGORIES.map((cat, catIndex) => (
          <div key={cat.name} data-category-index={catIndex}>
            <div className="emoji-category-label">{cat.name}</div>
            <div className="emoji-grid">
              {cat.emojis.map((emoji, emojiIndex) => (
                <button
                  key={`${catIndex}-${emojiIndex}`}
                  className="emoji-item"
                  onClick={() => handleEmojiClick(emoji)}
                  title={emoji}
                >
                  {emoji}
                </button>
              ))}
            </div>
          </div>
        ))}
      </div>
    </div>
  );
}